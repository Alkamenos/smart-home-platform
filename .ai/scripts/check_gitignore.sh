#!/usr/bin/env bash
#
# Проверка .gitignore: файл обязан совпадать с эталоном.
#
# Зачем проверка, если .gitignore и так запрещено правилами: правило запрещает
# редактирование, а проверка ловит само редактирование. Одно без другого не
# работает — это выяснилось на практике.
#
# Что было сломано
# ----------------
#
# Скрипта не существовало, хотя на него ссылались и pre-commit, и это сообщение.
# Pre-commit проверял `if [[ -x ... ]]` — отсутствующий файл просто не проходил
# по условию, и проверка молча пропускалась. То есть файл можно было править
# беспрепятственно.
#
# Молчание выглядело как «проверка прошла». Именно так и вышло: два коммита
# (`5dad5f8`, `848b140`) добавили в .gitignore правила для ключа шифрования и
# для `.env.*` — а эталон `.ai/templates/qwen.gitignore.fix` остался прежним.
# `run_checks.sh` сверял файл с устаревшим эталоном и падал на каждом запуске,
# предлагая «восстановить .gitignore из шаблона», то есть откатить правила
# безопасности и вернуть в индекс каталоги с манифестом и копиями бэкапов.
#
# Обе проверки молчали о разном: pre-commit — о самом факте правки, run_checks —
# сравнивал с неверным эталоном. Теперь эталон отражает фактическое состояние,
# а скрипт действительно существует.
#
# Что проверяется
# ---------------
#
# 1. Эталон существует — иначе сравнивать не с чем.
# 2. Файл совпадает с эталоном.
# 3. Правила безопасности на месте: ключ шифрования, `.env.*`, рабочие каталоги
#    развёртывания. Отдельная проверка, потому что совпадение с эталоном не
#    защищает от того, что эталон испорчен: ошибся тот, кто его обновлял, —
#    ошибся бы и здесь.
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TEMPLATE="$ROOT/.ai/templates/qwen.gitignore.fix"
TARGET="$ROOT/.gitignore"

# Правила, без которых секрет или рабочие данные оказываются в индексе.
# Проверяются именно здесь, а не только сверкой с эталоном: сверка доказывает
# тождество файлов, но не то, что в эталоне написано правильное.
REQUIRED_RULES=(
    "encryption.key"
    ".env.*"
    "!.env.example"
    "deploy/docker/config/"
    "deploy/docker/data/"
    "deploy/docker/backups/"
)

if [[ ! -f "$TEMPLATE" ]]; then
    echo "❌ Эталон .gitignore не найден: $TEMPLATE" >&2
    echo "   Без него правка .gitignore не проверяется." >&2
    exit 1
fi

if ! diff -q "$TEMPLATE" "$TARGET" >/dev/null 2>&1; then
    echo "❌ .gitignore расходится с эталоном." >&2
    echo >&2
    diff "$TEMPLATE" "$TARGET" >&2 || true
    echo >&2
    echo "⛔ Если правка намеренная (например, новое правило безопасности)," >&2
    echo "   обнови эталон ВМЕСТЕ с файлом — иначе следующий запуск" >&2
    echo "   run_checks.sh упадёт и предложит откатить твою же правку:" >&2
    echo >&2
    echo "   cp .gitignore .ai/templates/qwen.gitignore.fix" >&2
    exit 1
fi

for rule in "${REQUIRED_RULES[@]}"; do
    if ! grep -qxF "$rule" "$TARGET"; then
        echo "❌ В .gitignore нет обязательного правила: $rule" >&2
        echo "   Без него секрет или рабочие данные могут попасть в индекс." >&2
        exit 1
    fi
done

echo "✅ .gitignore совпадает с эталоном, правила безопасности на месте"
